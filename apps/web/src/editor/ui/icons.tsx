/** Icon ids of the editor registry → lucide components (the registry stays UI-free). */
import {
  AtSign,
  Bookmark,
  Calendar,
  ChevronRight,
  Code,
  Columns3,
  Copy,
  CornerUpRight,
  FileSymlink,
  FilePlus,
  FileText,
  Heading1,
  Heading2,
  Heading3,
  Image,
  Info,
  Link,
  List,
  ListOrdered,
  ListTree,
  Minus,
  Palette,
  Paperclip,
  Quote,
  Repeat,
  Sigma,
  SquareCheck,
  SquareFunction,
  Table,
  Trash2,
  Type,
  type LucideIcon,
} from 'lucide-react';

const ICONS: Record<string, LucideIcon> = {
  type: Type,
  'heading-1': Heading1,
  'heading-2': Heading2,
  'heading-3': Heading3,
  list: List,
  'list-ordered': ListOrdered,
  'square-check': SquareCheck,
  'chevron-right': ChevronRight,
  quote: Quote,
  info: Info,
  minus: Minus,
  'file-plus': FilePlus,
  'file-symlink': FileSymlink,
  image: Image,
  paperclip: Paperclip,
  bookmark: Bookmark,
  code: Code,
  table: Table,
  columns: Columns3,
  sigma: Sigma,
  'list-tree': ListTree,
  'at-sign': AtSign,
  'file-text': FileText,
  calendar: Calendar,
  'square-function': SquareFunction,
  repeat: Repeat,
  palette: Palette,
  copy: Copy,
  'corner-up-right': CornerUpRight,
  link: Link,
  trash: Trash2,
};

export function RegistryIcon({ id, className }: { id: string; className?: string }) {
  const Icon = ICONS[id] ?? FileText;
  return <Icon className={className ?? 'size-4'} aria-hidden="true" />;
}
